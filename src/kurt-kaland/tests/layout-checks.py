"""A közös Playwright-futtató által behívott képernyő- és animációtesztek."""


def run_wait_settings_checks(browser, url, out, check, watch):
    context = browser.new_context(viewport={"width": 1920, "height": 1080})
    page = context.new_page()
    watch(page)
    page.goto(url)
    page.wait_for_function("!!window.kurtTest")
    page.clock.install()
    # A kattintások közben se teljen valódi idő: a várakozás hosszát pontosan mérjük.
    page.clock.pause_at("2030-01-01T00:00:00Z")
    page.locator("#settings-toggle").click()
    for height in (1080, 900):
        page.set_viewport_size({"width": 1920, "height": height})
        result = page.locator("#settings").evaluate("""el=>{
          const r=el.getBoundingClientRect(), s=getComputedStyle(el);
          const controls=[...el.querySelectorAll('input,select,button')].filter(e=>e.checkVisibility());
          return {full:r.x===0&&r.y===0&&r.width===innerWidth&&r.height===innerHeight,
            opaque:s.backgroundColor==='rgb(33, 30, 54)', noScroll:el.scrollHeight<=el.clientHeight+1,
            inside:controls.every(e=>{const b=e.getBoundingClientRect();return b.top>=0&&b.bottom<=innerHeight&&b.left>=0&&b.right<=innerWidth;}),
            outside:controls.filter(e=>{const b=e.getBoundingClientRect();return b.top<0||b.bottom>innerHeight||b.left<0||b.right>innerWidth;}).map(e=>({id:e.id,bottom:e.getBoundingClientRect().bottom})),
            gameHidden:getComputedStyle(document.querySelector('.game-shell')).visibility==='hidden'};
        }""")
        page.screenshot(path=str(out / f"settings-fullscreen-1920x{height}.png"))
        check(all(result[key] for key in ("full", "opaque", "noScroll", "inside", "gameHidden")), f"Opaque fullscreen settings fit without scrolling at 1920x{height}: {result}")
    page.locator("#settings-close").focus()
    page.keyboard.press("Tab")
    check(page.locator("#settings-dismiss").evaluate("el=>el===document.activeElement"), "Settings keyboard focus cannot escape to the hidden game")
    page.locator("#mode").select_option("hold")
    page.locator("#speed").select_option("1.5")
    page.locator("#rest").select_option("3")
    page.locator("#settings-close").click()
    page.set_viewport_size({"width": 1280, "height": 720})
    page.locator("#demo-start").click()
    check(page.locator("#wait-indicator").is_visible() and page.locator("#progress-row").is_hidden() and page.locator("#wait-count").inner_text() == "3", "Waiting uses a countdown badge, never the note-holding bar")
    page.clock.run_for(1100)
    check(page.locator("#wait-count").inner_text() == "2", "Single preparation countdown decreases from 3 to 2")
    page.screenshot(path=str(out / "wait-countdown.png"))
    page.locator("#pause").click()
    before = page.evaluate("kurtTest.snapshot().phaseTime")
    page.clock.run_for(1000)
    check(page.evaluate("kurtTest.snapshot().phaseTime") == before and page.locator("#progress-row").is_hidden(), "Manual pause freezes the countdown without showing a fake hold bar")
    page.locator("#pause").click()
    page.clock.run_for(1800)
    check(page.evaluate("kurtTest.snapshot().phase") == "approach", "The selected 3-second preparation is respected")
    page.clock.run_for(300)
    check(page.evaluate("kurtTest.snapshot().phase") == "play" and page.locator("#progress-row").is_visible() and page.locator("#wait-indicator").is_hidden(), "Countdown switches directly to the actual note-holding meter")
    page.locator("#scene").click(position={"x": 20, "y": 20})
    page.keyboard.down("1")
    page.clock.run_for(1100)
    page.keyboard.up("1")
    page.clock.run_for(1300)
    snapshot = page.evaluate("kurtTest.snapshot()")
    check(snapshot["taskIndex"] == 1 and snapshot["phase"] == "approach", "After success the next task is already shown during the same rest/preparation interval")
    remaining = 3 - snapshot["phaseTime"]
    page.clock.run_for(max(0, int((remaining - .15) * 1000)))
    check(page.evaluate("kurtTest.snapshot().phase") == "approach", "No extra rest phase is inserted before the next task")
    page.clock.run_for(250)
    check(page.evaluate("kurtTest.snapshot().phase") == "play" and page.evaluate("kurtTest.snapshot().taskIndex") == 1, "Next task starts after one countdown, not two consecutive waits")
    context.close()


def run_preference_checks(browser, url, check, watch):
    context = browser.new_context()
    page = context.new_page()
    watch(page)
    page.goto(url)
    page.wait_for_function("!!window.kurtTest")
    check(page.evaluate("kurtTest.snapshot().settings.rest") == 3, "Fresh default rest is 3 seconds")
    page.locator("#settings-toggle").click()
    names = page.locator("#note-editor input[maxlength]").evaluate_all("els=>els.map(el=>el.value)")
    check(names == ["B♭3", "C4", "D4", "Esz4", "F4"], "Default labels name the actual sounding notes, not a guessed horn notation")
    page.evaluate("""() => localStorage.setItem('kurt-kaland-v1', JSON.stringify({settings:{rest:5},stickers:2,
      notes:[233.0819,261.6256,293.6648,311.127,349.2282].map((hz,i)=>({hz,label:i===1?'Tanári Dó':`${i+1}. hang`,approved:true}))}))""")
    page.reload()
    page.wait_for_function("!!window.kurtTest")
    page.locator("#settings-toggle").click()
    names = page.locator("#note-editor input[maxlength]").evaluate_all("els=>els.map(el=>el.value)")
    check(page.locator("#rest").input_value() == "3" and names[0] == "B♭3" and names[1] == "Tanári Dó", "Legacy defaults migrate to 3 seconds and real names; custom names remain intact")
    check(page.locator(".note-row.approved").count() == 5 and "2" in page.locator("#collection").text_content(), "Migration keeps approved pitches and stickers")
    page.locator("#note-editor input[type=number]").nth(0).fill("440")
    page.locator("#note-editor input[type=number]").nth(0).dispatch_event("change")
    check(page.locator("#note-editor input[maxlength]").nth(0).input_value() == "A4", "Automatic note name follows frequency edits")
    page.locator("#note-editor input[type=number]").nth(1).fill("445")
    page.locator("#note-editor input[type=number]").nth(1).dispatch_event("change")
    check(page.locator("#note-editor input[maxlength]").nth(1).input_value() == "Tanári Dó", "Custom teacher's label survives frequency edits")
    page.locator("#note-editor input[maxlength]").nth(2).fill("1. hang")
    page.locator("#note-editor input[maxlength]").nth(2).dispatch_event("change")
    page.locator("#rest").select_option("5")
    page.reload()
    page.wait_for_function("!!window.kurtTest")
    check(page.evaluate("kurtTest.snapshot().settings.rest") == 5, "Explicitly chosen 5-second rest survives reload")
    page.locator("#settings-toggle").click()
    check(page.locator("#note-editor input[maxlength]").nth(2).input_value() == "1. hang", "Even a deliberately chosen generic custom label is preserved")
    page.locator("#rest").select_option("8")
    page.reload()
    page.wait_for_function("!!window.kurtTest")
    check(page.evaluate("kurtTest.snapshot().settings.rest") == 8, "Longer chosen rest remains available")
    context.close()


def run_layout_checks(browser, url, out, check, watch):
    context = browser.new_context(viewport={"width": 1280, "height": 720})
    page = context.new_page()
    watch(page)
    page.goto(url)
    page.wait_for_function("!!window.kurtTest")
    page.clock.install()
    page.locator("#settings-toggle").click()
    page.locator("#note-count").select_option("5")
    page.locator("#mode").select_option("hold")
    page.locator("#speed").select_option("1.5")
    page.locator("#settings-close").click()
    page.locator("#demo-start").click()
    check("felhő" in page.locator("#hint").inner_text() and "buck" not in page.locator("#hint").inner_text(), "Hold preparation explains the cloud, not jumping")
    page.clock.run_for(2000)

    for width, height in [(1280, 720), (1366, 600), (1024, 600), (390, 844), (320, 568), (320, 480), (844, 390), (667, 375), (568, 320)]:
        page.set_viewport_size({"width": width, "height": height})
        page.clock.run_for(150)
        result = page.evaluate("""() => {
          const ids=['scene','control-dock','task-label','phase','hint','task-progress','progress-label','demo-keys','pause','finish','settings-toggle'];
          const outside=ids.filter(id=>{const r=document.getElementById(id).getBoundingClientRect();return r.top<0 || r.left<0 || r.right>innerWidth+.5 || r.bottom>innerHeight+.5;});
          const canvas=document.getElementById('scene').getBoundingClientRect();
          const dock=document.getElementById('control-dock').getBoundingClientRect();
          return {outside, noScroll:document.documentElement.scrollWidth<=innerWidth && document.documentElement.scrollHeight<=innerHeight+1, stage:canvas.height,
            noOverlap:canvas.bottom<=dock.top+1, touch:[...document.querySelectorAll('#demo-keys button')].every(b=>b.getBoundingClientRect().width>=44 && b.getBoundingClientRect().height>=44),
            panels:document.querySelectorAll('#control-dock').length===1 && !document.querySelector('#demo-instruction')};
        }""")
        check(not result["outside"] and result["noScroll"] and result["noOverlap"] and result["stage"] >= 125 and result["touch"] and result["panels"], f"Everything visible, one panel, no scrolling: {width}x{height}: {result}")
        page.screenshot(path=str(out / f"layout-{width}x{height}.png"))
    page.set_viewport_size({"width": 1280, "height": 720})
    page.locator("#scene").click(position={"x": 20, "y": 20})
    page.keyboard.down("1")
    page.clock.run_for(80)
    motion = page.evaluate("kurtTest.snapshot().motion")
    check(0 < motion["floatLift"] < .9, "Sustained note starts a smooth ascent")
    page.clock.run_for(350)
    page.screenshot(path=str(out / "hold-meter-visible.png"))
    check("/ 1,0 mp" in page.locator("#progress-label").inner_text() and float(page.locator("#task-progress").evaluate("el => el.parentElement.getAttribute('aria-valuenow')")) > 20, "Hold meter and numeric duration update in the same visible panel")
    check(page.locator("#world-label").inner_text() == "FELHŐLIFT" and "Tartsd végig" in page.locator("#hint").inner_text(), "Cloud task clearly asks for one continuous hold")
    page.set_viewport_size({"width": 390, "height": 844})
    page.clock.run_for(80)
    page.screenshot(path=str(out / "cloud-mobile-floating.png"))
    page.set_viewport_size({"width": 844, "height": 390})
    page.clock.run_for(80)
    page.screenshot(path=str(out / "cloud-landscape-floating.png"))
    page.set_viewport_size({"width": 1280, "height": 720})
    before_release = page.evaluate("kurtTest.snapshot().motion.floatLift")
    page.keyboard.up("1")
    page.clock.run_for(350)
    check(page.evaluate("kurtTest.snapshot().motion.floatLift") < before_release and page.evaluate("kurtTest.snapshot().score") == 0, "Releasing early gently lowers the cloud without a false success")
    page.keyboard.down("1")
    page.clock.run_for(1100)
    page.keyboard.up("1")
    page.clock.run_for(80)
    check(page.evaluate("kurtTest.snapshot().score") == 1 and "öt csillag" in page.locator("#hint").inner_text() and "ugrás" not in page.locator("#hint").inner_text(), "Completed cloud hold celebrates all five stars, not a jump")
    page.screenshot(path=str(out / "cloud-success.png"))
    page.locator("#pause").click()
    before = page.evaluate("kurtTest.snapshot().motion")
    page.clock.run_for(1000)
    check(page.evaluate("kurtTest.snapshot().motion") == before, "Pause freezes bunny animation as well as practice")
    page.locator("#settings-toggle").click()
    check(page.locator("#settings").evaluate("el=>el.getBoundingClientRect().width===innerWidth && getComputedStyle(el).overflowY==='auto'"), "Fullscreen settings remain scrollable on smaller screens")
    page.locator("#mode").select_option("short")
    page.locator("#settings-close").click()
    page.locator("#finish").click()
    page.locator("#again").click()
    page.clock.run_for(3200)
    page.locator("#scene").click(position={"x": 20, "y": 20})
    page.keyboard.down("1")
    page.clock.run_for(160)
    takeoff = page.evaluate("kurtTest.snapshot().motion")
    check(takeoff["hopActive"] and 0 < takeoff["hop"]["lift"] < .5, "Jump takes off from ground, not instantly at peak")
    page.keyboard.up("1")
    page.clock.run_for(280)
    peak = page.evaluate("kurtTest.snapshot().motion")
    check(peak["hop"]["lift"] > .8, "Jump follows arc above the obstacle")
    page.screenshot(path=str(out / "jump-apex.png"))
    page.clock.run_for(450)
    landed = page.evaluate("kurtTest.snapshot().motion")
    check(not landed["hopActive"] and landed["hop"]["lift"] == 0 and landed["cleared"] == 1, "Bunny lands beyond the obstacle")
    page.screenshot(path=str(out / "obstacle-after-landing.png"))
    page.clock.run_for(600)
    after = page.evaluate("kurtTest.snapshot()")
    check(after["phase"] == "approach" and after["motion"]["departures"][0]["exit"] > landed["obstacleExit"], "Cleared obstacles keep moving left while the next task prepares")
    page.screenshot(path=str(out / "obstacle-exiting.png"))
    page.locator("#pause").click()
    offset = page.evaluate("kurtTest.snapshot().motion.departures")
    page.clock.run_for(500)
    check(page.evaluate("kurtTest.snapshot().motion.departures") == offset, "Pause also freezes departing obstacles")
    context.close()
